import React, { useMemo, useState } from 'react';
import {
  Archive,
  CheckSquare,
  Copy,
  CreditCard,
  Edit3,
  Plus,
  Sparkles,
  Square,
  Trash2,
  X,
} from 'lucide-react';
import { useApp } from '../context/AppContext';
import { ORDER_STATUSES, Order, OrderStatus, PAYMENT_METHODS, PaymentMethod } from '../types';
import {
  calculateOrderBalance,
  formatCurrency,
  formatShortDate,
  roundMoney,
  sanitizeUserFacingMessage,
} from '../utils/businessLogic';
import { useLockBodyScroll } from '../utils/useLockBodyScroll';
import { ConfirmDialog } from './ConfirmDialog';

export function OrderDetailDrawer({
  order,
  onClose,
}: {
  order: Order;
  onClose: () => void;
}) {
  const {
    business,
    payments,
    tasks,
    todayIso,
    updateOrderStatus,
    saveOrder,
    recordPayment,
    saveTask,
    toggleTask,
    duplicateOrder,
    archiveOrder,
    deleteOrder,
    openOrderModal,
    openMessageModal,
    setActiveSection,
    setSelectedCustomerId,
  } = useApp();

  useLockBodyScroll(true);

  const [showPayForm, setShowPayForm] = useState(false);
  const [payAmount, setPayAmount] = useState(
    order.remainingBalance > 0 ? String(order.remainingBalance) : ''
  );
  const [payDate, setPayDate] = useState(todayIso);
  const [payMethod, setPayMethod] = useState<PaymentMethod>('Bank transfer');
  const [payNotes, setPayNotes] = useState('');
  const [payError, setPayError] = useState<string | null>(null);
  const [savingPay, setSavingPay] = useState(false);

  const [newTaskTitle, setNewTaskTitle] = useState('');
  const [trackingDraft, setTrackingDraft] = useState(order.trackingNumber || '');
  const [confirmDelete, setConfirmDelete] = useState(false);

  const orderPayments = useMemo(
    () => payments.filter((p) => p.orderId === order.id),
    [payments, order.id]
  );

  const hasPaymentHistory = order.amountPaid > 0 || orderPayments.length > 0;

  const orderTasks = useMemo(
    () => tasks.filter((t) => t.orderId === order.id),
    [tasks, order.id]
  );

  const bal = calculateOrderBalance(
    order.totalPrice,
    order.amountPaid,
    order.depositRequired
  );

  const handleRecordPayment = async (e: React.FormEvent) => {
    e.preventDefault();
    setPayError(null);
    const num = roundMoney(Number(payAmount));
    if (!Number.isFinite(num) || num <= 0) {
      setPayError('Enter a payment amount greater than zero.');
      return;
    }
    const remaining = roundMoney(order.remainingBalance);
    if (num > remaining + 0.005) {
      setPayError(`Only ${formatCurrency(remaining, business.currency)} remains on this order.`);
      return;
    }

    setSavingPay(true);
    try {
      await recordPayment(order.id, {
        amount: num,
        date: payDate,
        method: payMethod,
        notes: payNotes,
      });
      setShowPayForm(false);
      setPayNotes('');
      setPayError(null);
      const nextRem = Math.max(0, roundMoney(remaining - num));
      setPayAmount(nextRem > 0 ? String(nextRem) : '');
    } catch (err) {
      setPayError(
        sanitizeUserFacingMessage(err, 'Could not record payment right now. Please try again.')
      );
    } finally {
      setSavingPay(false);
    }
  };

  const handleAddOrderTask = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTaskTitle.trim()) return;
    await saveTask({
      title: newTaskTitle.trim(),
      customerId: order.customerId,
      customerName: order.customerName,
      orderId: order.id,
      orderNumber: order.orderNumber,
      dueDate: order.dueDate || todayIso,
      priority: 'Medium',
      completed: false,
      autoGenerated: false,
    });
    setNewTaskTitle('');
  };

  const handleSaveTracking = async () => {
    if (trackingDraft.trim() === order.trackingNumber) return;
    await saveOrder({
      ...order,
      trackingNumber: trackingDraft.trim(),
    });
  };

  return (
    <>
      <div
        className="fixed inset-0 z-40 flex justify-end bg-black/40 backdrop-blur-xs"
        role="dialog"
        aria-modal="true"
        aria-labelledby="order-drawer-title"
        onClick={(e) => {
          if (e.target === e.currentTarget) onClose();
        }}
      >
        <div className="flex h-full w-full max-w-xl flex-col overflow-y-auto overscroll-contain border-l border-stone-200 bg-white p-4 pb-safe shadow-2xl sm:p-6 dark:border-zinc-800 dark:bg-zinc-900">
          {/* Top Bar */}
          <div className="flex items-start justify-between gap-4 border-b border-stone-200 pb-4 dark:border-zinc-800">
            <div>
              <div className="flex items-center gap-2 text-xs text-stone-500 dark:text-zinc-400">
                <span className="font-mono font-medium">{order.orderNumber}</span>
                <span aria-hidden="true">·</span>
                <span>Ordered {formatShortDate(order.orderDate)}</span>
                {order.archived && (
                  <>
                    <span aria-hidden="true">·</span>
                    <span className="font-semibold text-amber-700 dark:text-amber-400">
                      Archived
                    </span>
                  </>
                )}
              </div>
              <h2
                id="order-drawer-title"
                className="mt-1 font-display text-xl font-semibold text-stone-900 dark:text-zinc-100"
              >
                {order.product}
              </h2>
              <button
                type="button"
                onClick={() => {
                  onClose();
                  setActiveSection('customers');
                  setSelectedCustomerId(order.customerId);
                }}
                className="mt-0.5 text-sm font-medium text-stone-700 underline underline-offset-4 hover:text-stone-950 dark:text-zinc-300 dark:hover:text-white"
              >
                {order.customerName}
              </button>
            </div>

            <button
              type="button"
              onClick={onClose}
              aria-label="Close order details"
              className="rounded-lg p-1.5 text-stone-400 hover:bg-stone-100 hover:text-stone-700 dark:hover:bg-zinc-800 dark:hover:text-zinc-200"
            >
              <X className="h-5 w-5" />
            </button>
          </div>

          {/* Primary Actions Bar */}
          <div className="mt-4 flex flex-wrap items-center justify-between gap-3">
            <div className="flex items-center gap-2">
              <label htmlFor="drawer-status-select" className="text-xs font-medium text-stone-500">
                Status:
              </label>
              <select
                id="drawer-status-select"
                value={order.status}
                disabled={order.status === 'Cancelled'}
                onChange={(e) => void updateOrderStatus(order.id, e.target.value as OrderStatus)}
                className="rounded-xl border border-stone-200 bg-stone-50 px-3 py-1.5 text-xs font-semibold text-stone-900 focus:outline-none disabled:opacity-60 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-100"
              >
                {ORDER_STATUSES.map((st) => (
                  <option key={st} value={st}>
                    {st}
                  </option>
                ))}
              </select>
            </div>

            <div className="flex flex-wrap items-center gap-2">
              <button
                type="button"
                onClick={() =>
                  openMessageModal({
                    customerName: order.customerName,
                    order,
                    defaultPreset:
                      order.remainingBalance > 0
                        ? 'payment_reminder'
                        : order.status === 'Ready'
                          ? 'order_ready'
                          : 'preview_ready',
                  })
                }
                className="inline-flex items-center gap-1.5 rounded-xl border border-stone-200 bg-white px-3 py-1.5 text-xs font-semibold text-stone-800 hover:bg-stone-50 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-200"
              >
                <Sparkles className="h-3.5 w-3.5" aria-hidden="true" />
                Write Message
              </button>

              {order.status !== 'Cancelled' && (
                <button
                  type="button"
                  onClick={() => openOrderModal('manual', order)}
                  aria-label="Edit order"
                  className="inline-flex items-center gap-1 rounded-xl border border-stone-200 px-2.5 py-1.5 text-xs font-medium text-stone-700 hover:bg-stone-50 dark:border-zinc-700 dark:text-zinc-300 dark:hover:bg-zinc-800"
                >
                  <Edit3 className="h-3.5 w-3.5" />
                  Edit
                </button>
              )}
            </div>
          </div>

          {/* Payment Tracking Section */}
          <section className="mt-6 rounded-2xl border border-stone-200 bg-stone-50/70 p-5 dark:border-zinc-800 dark:bg-zinc-950">
            <div className="flex items-center justify-between gap-2">
              <div className="flex items-center gap-2">
                <CreditCard className="h-4 w-4 text-stone-600 dark:text-zinc-400" />
                <h3 className="text-sm font-semibold text-stone-900 dark:text-zinc-100">
                  Payment Tracking
                </h3>
              </div>
              <span className="font-mono text-xs font-semibold text-stone-700 tabular-nums dark:text-zinc-300">
                {bal.percentPaid}% paid
              </span>
            </div>

            <div className="mt-3 flex items-baseline justify-between">
              <p className="font-mono text-sm font-semibold text-stone-900 tabular-nums dark:text-zinc-100">
                {formatCurrency(order.amountPaid, business.currency)} /{' '}
                {formatCurrency(order.totalPrice, business.currency)} paid
              </p>
              <p
                className={`font-mono text-xs font-medium tabular-nums ${
                  order.remainingBalance > 0
                    ? 'text-amber-700 dark:text-amber-400'
                    : 'text-emerald-700 dark:text-emerald-400'
                }`}
              >
                {order.remainingBalance > 0
                  ? `${formatCurrency(order.remainingBalance, business.currency)} remaining`
                  : 'Paid in full'}
              </p>
            </div>

            {/* Progress Bar */}
            <svg
              viewBox="0 0 100 10"
              preserveAspectRatio="none"
              aria-hidden="true"
              className="mt-2.5 h-2.5 w-full overflow-hidden rounded-full bg-stone-200 dark:bg-zinc-800"
            >
              <rect
                x="0"
                y="0"
                width={bal.percentPaid}
                height="10"
                className={
                  bal.isFullyPaid
                    ? 'fill-emerald-600 dark:fill-emerald-500'
                    : 'fill-stone-900 dark:fill-zinc-200'
                }
              />
            </svg>

            {order.remainingBalance > 0 && order.status !== 'Cancelled' && (
              <div className="mt-4">
                {!showPayForm ? (
                  <button
                    type="button"
                    onClick={() => {
                      setPayError(null);
                      setPayAmount(String(order.remainingBalance));
                      setShowPayForm(true);
                    }}
                    className="rounded-xl bg-stone-900 px-3.5 py-2 text-xs font-semibold text-white hover:bg-stone-800 dark:bg-zinc-100 dark:text-zinc-900"
                  >
                    Record payment
                  </button>
                ) : (
                  <form
                    onSubmit={handleRecordPayment}
                    noValidate
                    className="mt-3 space-y-3 border-t border-stone-200 pt-3 dark:border-zinc-800"
                  >
                    {payError && (
                      <div
                        role="alert"
                        className="rounded-lg border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700 dark:border-red-900/50 dark:bg-red-950/30 dark:text-red-300"
                      >
                        {payError}
                      </div>
                    )}

                    <div className="grid grid-cols-2 gap-2.5 sm:grid-cols-3">
                      <div>
                        <label
                          htmlFor="rec-pay-amt"
                          className="block text-[11px] font-medium text-stone-600 dark:text-zinc-400"
                        >
                          Amount ({business.currency})
                        </label>
                        <input
                          id="rec-pay-amt"
                          type="number"
                          step="0.01"
                          min="0.01"
                          required
                          value={payAmount}
                          onChange={(e) => {
                            setPayAmount(e.target.value);
                            if (payError) setPayError(null);
                          }}
                          className="mt-1 w-full rounded-lg border border-stone-200 bg-white px-2.5 py-1.5 font-mono text-xs text-stone-900 tabular-nums dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-100"
                        />
                      </div>

                      <div>
                        <label
                          htmlFor="rec-pay-method"
                          className="block text-[11px] font-medium text-stone-600 dark:text-zinc-400"
                        >
                          Method
                        </label>
                        <select
                          id="rec-pay-method"
                          value={payMethod}
                          onChange={(e) => setPayMethod(e.target.value as PaymentMethod)}
                          className="mt-1 w-full rounded-lg border border-stone-200 bg-white px-2.5 py-1.5 text-xs text-stone-900 dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-100"
                        >
                          {PAYMENT_METHODS.map((m) => (
                            <option key={m} value={m}>
                              {m}
                            </option>
                          ))}
                        </select>
                      </div>

                      <div className="col-span-2 sm:col-span-1">
                        <label
                          htmlFor="rec-pay-date"
                          className="block text-[11px] font-medium text-stone-600 dark:text-zinc-400"
                        >
                          Date
                        </label>
                        <input
                          id="rec-pay-date"
                          type="date"
                          value={payDate}
                          onChange={(e) => setPayDate(e.target.value)}
                          className="mt-1 w-full rounded-lg border border-stone-200 bg-white px-2.5 py-1.5 text-xs text-stone-900 dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-100"
                        />
                      </div>
                    </div>

                    <input
                      type="text"
                      value={payNotes}
                      onChange={(e) => setPayNotes(e.target.value)}
                      placeholder="Optional note (e.g. Final balance via PayPal)"
                      className="w-full rounded-lg border border-stone-200 bg-white px-2.5 py-1.5 text-xs text-stone-900 dark:border-zinc-700 dark:bg-zinc-900 dark:text-zinc-100"
                    />

                    <div className="flex items-center justify-end gap-2">
                      <button
                        type="button"
                        onClick={() => {
                          setPayError(null);
                          setShowPayForm(false);
                        }}
                        className="rounded-lg px-3 py-1.5 text-xs text-stone-600 hover:bg-stone-100 dark:text-zinc-400"
                      >
                        Cancel
                      </button>
                      <button
                        type="submit"
                        disabled={savingPay}
                        className="rounded-lg bg-stone-900 px-3.5 py-1.5 text-xs font-semibold text-white hover:bg-stone-800 dark:bg-zinc-100 dark:text-zinc-900"
                      >
                        {savingPay ? 'Saving…' : 'Save Payment'}
                      </button>
                    </div>
                  </form>
                )}
              </div>
            )}

            {/* Payment History */}
            {orderPayments.length > 0 && (
              <div className="mt-4 border-t border-stone-200 pt-3 dark:border-zinc-800">
                <p className="text-xs font-medium text-stone-500 dark:text-zinc-400">
                  Payment history
                </p>
                <ul className="mt-2 space-y-1.5">
                  {orderPayments.map((p) => (
                    <li
                      key={p.id}
                      className="flex items-center justify-between text-xs text-stone-700 dark:text-zinc-300"
                    >
                      <span>
                        {formatShortDate(p.date)} · {p.method}
                        {p.notes ? ` (${p.notes})` : ''}
                      </span>
                      <span className="font-mono font-semibold tabular-nums">
                        {formatCurrency(p.amount, business.currency)}
                      </span>
                    </li>
                  ))}
                </ul>
              </div>
            )}
          </section>

          {/* Order Specifications & Delivery */}
          <section className="mt-6 space-y-3 border-t border-stone-100 pt-5 text-sm dark:border-zinc-800">
            <div className="grid grid-cols-2 gap-4">
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Due date</p>
                <p className="mt-0.5 font-medium text-stone-900 dark:text-zinc-100">
                  {order.dueDate ? formatShortDate(order.dueDate) : 'Not set'}
                </p>
              </div>
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Quantity</p>
                <p className="mt-0.5 font-mono font-medium text-stone-900 tabular-nums dark:text-zinc-100">
                  {order.quantity}
                </p>
              </div>
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Delivery method</p>
                <p className="mt-0.5 font-medium text-stone-900 dark:text-zinc-100">
                  {order.deliveryMethod}
                </p>
              </div>
              <div>
                <label
                  htmlFor="drawer-tracking"
                  className="block text-xs text-stone-500 dark:text-zinc-400"
                >
                  Tracking number
                </label>
                <div className="mt-0.5 flex gap-1.5">
                  <input
                    id="drawer-tracking"
                    type="text"
                    disabled={order.status === 'Cancelled'}
                    value={trackingDraft}
                    onChange={(e) => setTrackingDraft(e.target.value)}
                    onBlur={() => void handleSaveTracking()}
                    placeholder="Add tracking…"
                    className="w-full rounded-lg border border-stone-200 bg-stone-50 px-2.5 py-1 font-mono text-xs text-stone-900 dark:border-zinc-700 dark:bg-zinc-800 dark:text-zinc-100"
                  />
                </div>
              </div>
            </div>

            {order.description && (
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Description</p>
                <p className="mt-0.5 text-sm text-stone-800 dark:text-zinc-200">
                  {order.description}
                </p>
              </div>
            )}

            {order.customerNotes && (
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Customer notes</p>
                <p className="mt-0.5 text-sm text-stone-800 dark:text-zinc-200">
                  {order.customerNotes}
                </p>
              </div>
            )}

            {order.internalNotes && (
              <div>
                <p className="text-xs text-stone-500 dark:text-zinc-400">Internal notes</p>
                <p className="mt-0.5 text-sm text-stone-700 dark:text-zinc-300">
                  {order.internalNotes}
                </p>
              </div>
            )}
          </section>

          {/* Order Checklist Tasks */}
          <section className="mt-6 border-t border-stone-100 pt-5 dark:border-zinc-800">
            <h3 className="text-sm font-semibold text-stone-900 dark:text-zinc-100">
              Order Tasks ({orderTasks.filter((t) => t.completed).length}/{orderTasks.length})
            </h3>

            {orderTasks.length > 0 && (
              <ul className="mt-3 space-y-2">
                {orderTasks.map((t) => (
                  <li key={t.id}>
                    <button
                      type="button"
                      onClick={() => void toggleTask(t.id)}
                      className="flex w-full items-center gap-2.5 rounded-lg py-1 text-left text-sm hover:opacity-80"
                    >
                      {t.completed ? (
                        <CheckSquare className="h-4 w-4 shrink-0 text-emerald-600 dark:text-emerald-400" />
                      ) : (
                        <Square className="h-4 w-4 shrink-0 text-stone-400 dark:text-zinc-500" />
                      )}
                      <span
                        className={
                          t.completed
                            ? 'text-stone-400 line-through dark:text-zinc-500'
                            : 'text-stone-800 dark:text-zinc-200'
                        }
                      >
                        {t.title}
                      </span>
                    </button>
                  </li>
                ))}
              </ul>
            )}

            <form onSubmit={handleAddOrderTask} className="mt-3 flex gap-2">
              <input
                type="text"
                value={newTaskTitle}
                onChange={(e) => setNewTaskTitle(e.target.value)}
                placeholder="Add a step for this order…"
                className="flex-1 rounded-xl border border-stone-200 bg-white px-3 py-1.5 text-xs text-stone-900 focus:outline-none dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
              />
              <button
                type="submit"
                aria-label="Add order task"
                className="inline-flex items-center gap-1 rounded-xl border border-stone-200 px-3 py-1.5 text-xs font-medium text-stone-700 hover:bg-stone-50 dark:border-zinc-700 dark:text-zinc-300"
              >
                <Plus className="h-3.5 w-3.5" />
                Add
              </button>
            </form>
          </section>

          {/* Footer Secondary Actions: Duplicate, Archive, Delete */}
          <div className="mt-8 flex flex-wrap items-center justify-between gap-2 border-t border-stone-200 pt-4 text-xs dark:border-zinc-800">
            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={async () => {
                  const copy = await duplicateOrder(order.id);
                  if (copy) onClose();
                }}
                className="inline-flex items-center gap-1.5 rounded-lg border border-stone-200 px-3 py-1.5 font-medium text-stone-700 hover:bg-stone-50 dark:border-zinc-700 dark:text-zinc-300 dark:hover:bg-zinc-800"
              >
                <Copy className="h-3.5 w-3.5" />
                Duplicate
              </button>

              {order.status !== 'Cancelled' && (
                <button
                  type="button"
                  onClick={async () => {
                    await archiveOrder(order.id, !order.archived);
                    onClose();
                  }}
                  className="inline-flex items-center gap-1.5 rounded-lg border border-stone-200 px-3 py-1.5 font-medium text-stone-700 hover:bg-stone-50 dark:border-zinc-700 dark:text-zinc-300 dark:hover:bg-zinc-800"
                >
                  <Archive className="h-3.5 w-3.5" />
                  {order.archived ? 'Restore' : 'Archive'}
                </button>
              )}
            </div>

            <button
              type="button"
              onClick={() => setConfirmDelete(true)}
              className="inline-flex items-center gap-1.5 rounded-lg px-3 py-1.5 font-medium text-red-600 hover:bg-red-50 dark:text-red-400 dark:hover:bg-red-950/40"
            >
              <Trash2 className="h-3.5 w-3.5" />
              Delete order
            </button>
          </div>
        </div>
      </div>

      <ConfirmDialog
        open={confirmDelete}
        destructive={!hasPaymentHistory}
        title={
          hasPaymentHistory
            ? order.archived
              ? 'Paid orders cannot be deleted'
              : 'Archive order instead of deleting?'
            : `Delete ${order.orderNumber}?`
        }
        description={
          hasPaymentHistory
            ? `${order.orderNumber} has ${formatCurrency(order.amountPaid, business.currency)} in recorded payments. Paid orders cannot be permanently deleted so your Money & revenue totals stay accurate.${order.archived ? '' : ' Archive this order to remove it from your active list while keeping payment history intact.'}`
            : `This will permanently remove ${order.customerName}’s order (${order.product}) and its checklist tasks.`
        }
        confirmLabel={
          hasPaymentHistory
            ? order.archived
              ? 'Keep Archived'
              : 'Archive Order'
            : 'Delete Order'
        }
        onCancel={() => setConfirmDelete(false)}
        onConfirm={async () => {
          setConfirmDelete(false);
          if (hasPaymentHistory) {
            if (!order.archived && order.status !== 'Cancelled') {
              await archiveOrder(order.id, true);
              onClose();
            }
            return;
          }
          await deleteOrder(order.id);
          onClose();
        }}
      />
    </>
  );
}
