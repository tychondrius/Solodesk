import React, { useMemo, useState } from 'react';
import { CheckSquare, Plus, Square, Trash2, X } from 'lucide-react';
import { useApp } from '../context/AppContext';
import { TaskItem, TaskPriority } from '../types';
import { diffDays, formatRelativeDue } from '../utils/businessLogic';
import { ConfirmDialog } from './ConfirmDialog';

type TaskBucket = 'today' | 'upcoming' | 'overdue' | 'completed';

export function TasksView() {
  const {
    tasks,
    customers,
    orders,
    todayIso,
    saveTask,
    toggleTask,
    deleteTask,
    setActiveSection,
    setSelectedOrderId,
  } = useApp();

  const [bucket, setBucket] = useState<TaskBucket>('today');
  const [modalOpen, setModalOpen] = useState(false);
  const [title, setTitle] = useState('');
  const [customerId, setCustomerId] = useState('');
  const [orderId, setOrderId] = useState('');
  const [dueDate, setDueDate] = useState(todayIso);
  const [priority, setPriority] = useState<TaskPriority>('Medium');
  const [confirmDelete, setConfirmDelete] = useState<TaskItem | null>(null);

  const grouped = useMemo(() => {
    const today: TaskItem[] = [];
    const upcoming: TaskItem[] = [];
    const overdue: TaskItem[] = [];
    const completed: TaskItem[] = [];

    for (const t of tasks) {
      if (t.completed) {
        completed.push(t);
        continue;
      }
      const d = t.dueDate ? diffDays(todayIso, t.dueDate) : 0;
      if (d < 0) overdue.push(t);
      else if (d === 0) today.push(t);
      else upcoming.push(t);
    }

    return { today, upcoming, overdue, completed };
  }, [tasks, todayIso]);

  const activeList = grouped[bucket];

  const handleCreateTask = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!title.trim()) return;
    const cust = customers.find((c) => c.id === customerId);
    const ord = orders.find((o) => o.id === orderId);

    await saveTask({
      title: title.trim(),
      customerId: cust?.id || ord?.customerId || '',
      customerName: cust?.name || ord?.customerName || '',
      orderId: ord?.id || '',
      orderNumber: ord?.orderNumber || '',
      dueDate: dueDate || todayIso,
      priority,
      completed: false,
      autoGenerated: false,
    });

    setTitle('');
    setCustomerId('');
    setOrderId('');
    setDueDate(todayIso);
    setPriority('Medium');
    setModalOpen(false);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col justify-between gap-4 sm:flex-row sm:items-center">
        <div>
          <h2 className="font-display text-2xl font-semibold text-stone-900 dark:text-zinc-50">
            Tasks
          </h2>
          <p className="mt-0.5 text-sm text-stone-600 dark:text-zinc-400">
            Automatic order steps and your own studio to-dos, organised by deadline.
          </p>
        </div>

        <button
          type="button"
          onClick={() => setModalOpen(true)}
          className="inline-flex items-center gap-1.5 self-start rounded-xl bg-stone-900 px-4 py-2 text-sm font-semibold text-white hover:bg-stone-800 sm:self-center dark:bg-zinc-100 dark:text-zinc-900 dark:hover:bg-zinc-200"
        >
          <Plus className="h-4 w-4" aria-hidden="true" />
          New Task
        </button>
      </div>

      {/* Bucket Segmented Tabs */}
      <div className="flex items-center gap-1 overflow-x-auto rounded-xl bg-stone-100 p-1 dark:bg-zinc-900">
        {(
          [
            { id: 'today', label: 'Today', count: grouped.today.length },
            { id: 'overdue', label: 'Overdue', count: grouped.overdue.length },
            { id: 'upcoming', label: 'Upcoming', count: grouped.upcoming.length },
            { id: 'completed', label: 'Completed', count: grouped.completed.length },
          ] as { id: TaskBucket; label: string; count: number }[]
        ).map((tab) => {
          const active = bucket === tab.id;
          return (
            <button
              key={tab.id}
              type="button"
              onClick={() => setBucket(tab.id)}
              className={`flex items-center gap-2 rounded-lg px-3.5 py-1.5 text-xs font-medium transition-colors whitespace-nowrap shrink-0 ${
                active
                  ? 'bg-white text-stone-900 shadow-xs dark:bg-zinc-800 dark:text-zinc-100'
                  : 'text-stone-600 hover:text-stone-900 dark:text-zinc-400 dark:hover:text-zinc-200'
              }`}
            >
              <span>{tab.label}</span>
              <span className="font-mono text-[11px] text-stone-400 tabular-nums">
                {tab.count}
              </span>
            </button>
          );
        })}
      </div>

      {/* Task List */}
      <div className="rounded-2xl border border-stone-200 bg-white dark:border-zinc-800 dark:bg-zinc-900">
        {activeList.length === 0 ? (
          <div className="px-6 py-14 text-center">
            <CheckSquare
              className="mx-auto h-8 w-8 text-stone-400 dark:text-zinc-500"
              aria-hidden="true"
            />
            <h3 className="mt-3 text-sm font-semibold text-stone-900 dark:text-zinc-100">
              No {bucket} tasks
            </h3>
            <p className="mt-1 text-xs text-stone-500 dark:text-zinc-400">
              {bucket === 'overdue'
                ? 'Everything is on track — zero overdue tasks.'
                : 'Add a task manually or create a new order to generate steps automatically.'}
            </p>
          </div>
        ) : (
          <div className="divide-y divide-stone-100 dark:divide-zinc-800/70">
            {activeList.map((task) => (
              <div
                key={task.id}
                className="flex items-center justify-between gap-4 px-5 py-3.5 transition-colors hover:bg-stone-50/70 dark:hover:bg-zinc-800/40"
              >
                <div className="flex min-w-0 items-start gap-3">
                  <button
                    type="button"
                    onClick={() => void toggleTask(task.id)}
                    aria-label={
                      task.completed
                        ? `Mark "${task.title}" incomplete`
                        : `Complete "${task.title}"`
                    }
                    className="mt-0.5 text-stone-500 hover:text-stone-900 dark:text-zinc-400 dark:hover:text-zinc-100"
                  >
                    {task.completed ? (
                      <CheckSquare className="h-4 w-4 text-emerald-600 dark:text-emerald-400" />
                    ) : (
                      <Square className="h-4 w-4" />
                    )}
                  </button>

                  <div className="min-w-0">
                    <p
                      className={`text-sm font-medium ${
                        task.completed
                          ? 'text-stone-400 line-through dark:text-zinc-500'
                          : 'text-stone-900 dark:text-zinc-100'
                      }`}
                    >
                      {task.title}
                    </p>
                    <div className="mt-0.5 flex flex-wrap items-center gap-1.5 text-xs text-stone-500 dark:text-zinc-400">
                      <span>{formatRelativeDue(task.dueDate, todayIso)}</span>
                      <span aria-hidden="true">·</span>
                      <span
                        className={
                          task.priority === 'High'
                            ? 'font-semibold text-red-700 dark:text-red-400'
                            : ''
                        }
                      >
                        {task.priority} priority
                      </span>
                      {task.customerName && (
                        <>
                          <span aria-hidden="true">·</span>
                          <span>{task.customerName}</span>
                        </>
                      )}
                      {task.orderId && (
                        <>
                          <span aria-hidden="true">·</span>
                          <button
                            type="button"
                            onClick={() => {
                              setActiveSection('orders');
                              setSelectedOrderId(task.orderId);
                            }}
                            className="font-mono underline hover:text-stone-900 dark:hover:text-zinc-200"
                          >
                            {task.orderNumber || 'View order'}
                          </button>
                        </>
                      )}
                    </div>
                  </div>
                </div>

                <button
                  type="button"
                  onClick={() => setConfirmDelete(task)}
                  aria-label={`Delete task "${task.title}"`}
                  className="rounded-lg p-1.5 text-stone-400 hover:bg-stone-100 hover:text-red-600 dark:hover:bg-zinc-800 dark:hover:text-red-400"
                >
                  <Trash2 className="h-4 w-4" />
                </button>
              </div>
            ))}
          </div>
        )}
      </div>

      {/* Add Manual Task Modal */}
      {modalOpen && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 p-4 backdrop-blur-xs"
          role="dialog"
          aria-modal="true"
          aria-labelledby="new-task-title"
          onClick={(e) => {
            if (e.target === e.currentTarget) setModalOpen(false);
          }}
        >
          <div className="w-full max-w-md rounded-2xl border border-stone-200 bg-white p-6 shadow-2xl dark:border-zinc-800 dark:bg-zinc-900">
            <div className="flex items-center justify-between">
              <h3
                id="new-task-title"
                className="font-display text-lg font-semibold text-stone-900 dark:text-zinc-100"
              >
                New Task
              </h3>
              <button
                type="button"
                onClick={() => setModalOpen(false)}
                aria-label="Close new task modal"
                className="rounded-lg p-1 text-stone-400 hover:bg-stone-100 dark:hover:bg-zinc-800"
              >
                <X className="h-4 w-4" />
              </button>
            </div>

            <form onSubmit={handleCreateTask} className="mt-4 space-y-4">
              <div>
                <label
                  htmlFor="task-title-input"
                  className="block text-xs font-medium text-stone-700 dark:text-zinc-300"
                >
                  Task title *
                </label>
                <input
                  id="task-title-input"
                  type="text"
                  required
                  value={title}
                  onChange={(e) => setTitle(e.target.value)}
                  placeholder="e.g. Order A4 rigid kraft mailers"
                  className="mt-1 w-full rounded-xl border border-stone-200 bg-white px-3.5 py-2 text-sm text-stone-900 dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label
                    htmlFor="task-due-input"
                    className="block text-xs font-medium text-stone-700 dark:text-zinc-300"
                  >
                    Due date
                  </label>
                  <input
                    id="task-due-input"
                    type="date"
                    value={dueDate}
                    onChange={(e) => setDueDate(e.target.value)}
                    className="mt-1 w-full rounded-xl border border-stone-200 bg-white px-3 py-2 text-sm text-stone-900 dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
                  />
                </div>

                <div>
                  <label
                    htmlFor="task-priority-input"
                    className="block text-xs font-medium text-stone-700 dark:text-zinc-300"
                  >
                    Priority
                  </label>
                  <select
                    id="task-priority-input"
                    value={priority}
                    onChange={(e) => setPriority(e.target.value as TaskPriority)}
                    className="mt-1 w-full rounded-xl border border-stone-200 bg-white px-3 py-2 text-sm text-stone-900 dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
                  >
                    <option value="Low">Low</option>
                    <option value="Medium">Medium</option>
                    <option value="High">High</option>
                  </select>
                </div>
              </div>

              <div>
                <label
                  htmlFor="task-order-select"
                  className="block text-xs font-medium text-stone-700 dark:text-zinc-300"
                >
                  Related order (optional)
                </label>
                <select
                  id="task-order-select"
                  value={orderId}
                  onChange={(e) => {
                    const oid = e.target.value;
                    setOrderId(oid);
                    const found = orders.find((o) => o.id === oid);
                    if (found) setCustomerId(found.customerId);
                  }}
                  className="mt-1 w-full rounded-xl border border-stone-200 bg-white px-3 py-2 text-sm text-stone-900 dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
                >
                  <option value="">None</option>
                  {orders
                    .filter((o) => !o.archived)
                    .map((o) => (
                      <option key={o.id} value={o.id}>
                        {o.orderNumber} — {o.customerName} ({o.product})
                      </option>
                    ))}
                </select>
              </div>

              <div>
                <label
                  htmlFor="task-cust-select"
                  className="block text-xs font-medium text-stone-700 dark:text-zinc-300"
                >
                  Related customer (optional)
                </label>
                <select
                  id="task-cust-select"
                  value={customerId}
                  onChange={(e) => setCustomerId(e.target.value)}
                  className="mt-1 w-full rounded-xl border border-stone-200 bg-white px-3 py-2 text-sm text-stone-900 dark:border-zinc-700 dark:bg-zinc-950 dark:text-zinc-100"
                >
                  <option value="">None</option>
                  {customers.map((c) => (
                    <option key={c.id} value={c.id}>
                      {c.name}
                    </option>
                  ))}
                </select>
              </div>

              <div className="flex justify-end gap-2 pt-2">
                <button
                  type="button"
                  onClick={() => setModalOpen(false)}
                  className="rounded-xl border border-stone-200 px-4 py-2 text-xs font-medium text-stone-700 hover:bg-stone-50 dark:border-zinc-700 dark:text-zinc-300"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="rounded-xl bg-stone-900 px-4 py-2 text-xs font-semibold text-white hover:bg-stone-800 dark:bg-zinc-100 dark:text-zinc-900"
                >
                  Add Task
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      <ConfirmDialog
        open={Boolean(confirmDelete)}
        title="Delete task?"
        description={`Remove “${confirmDelete?.title}” from your task list?`}
        confirmLabel="Delete Task"
        onCancel={() => setConfirmDelete(null)}
        onConfirm={async () => {
          if (!confirmDelete) return;
          const id = confirmDelete.id;
          setConfirmDelete(null);
          await deleteTask(id);
        }}
      />
    </div>
  );
}
